export const STATE_NAMES: Record<string, string> = Object.fromEntries(
  Object.entries(US_STATES).map(([name, code]) => [
    code,
    name.replace(/\b\w/g, (letter) => letter.toUpperCase()).replace(" Of ", " of "),
  ]),
);

export function stateCode(value: string): string {
  const clean = value.trim();
  if (/^[A-Za-z]{2}$/.test(clean)) return clean.toUpperCase();
  return US_STATES[clean.toLowerCase()] ?? clean;
}
